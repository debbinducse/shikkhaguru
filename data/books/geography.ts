function withJobNote(chapter: Chapter): Chapter {
  const note = geographyJobNotes[chapter.slug];
  if (!note) return chapter;

  const factsTopic: Topic = {
    title: "সংখ্যায় এই অধ্যায়",
    summary: "চাকরির পরীক্ষায় সরাসরি আসা সংখ্যা, তারিখ ও পরিভাষা।",
    blocks: [
      {
        type: "table",
        caption: note.facts.caption,
        headers: ["বিষয়", "তথ্য"],
        rows: note.facts.rows,
        compact: true,
      },
      ...(note.tip
        ? [
            {
              type: "callout" as const,
              tone: "exam" as const,
              title: "মনে রাখুন",
              text: note.tip,
            },
          ]
        : []),
    ],
  };

  const qaTopic: Topic = {
    title: "এক নজরে প্রশ্নোত্তর",
    summary: "সংক্ষিপ্ত উত্তরের প্রস্তুতির জন্য দ্রুত রিভিশন।",
    blocks: [
      {
        type: "table",
        caption: "চাকরির পরীক্ষায় বারবার আসা প্রশ্ন",
        headers: ["প্রশ্ন", "উত্তর"],
        rows: note.qa.rows,
        compact: true,
      },
    ],
  };

  return {
    ...chapter,
    readingTime: chapter.readingTime + 8,
    veryImportant: [...chapter.veryImportant, factsTopic],
    important: [...chapter.important, qaTopic],
  };
}

